// Compêndio de rituais — Ordem Paranormal RPG (livro básico, 1º ao 4º círculo).
// Índice de referência: nome, círculo, elemento(s) e um resumo curto do efeito
// (descrição própria; a regra completa — execução, alcance, alvo, resistência,
// custo de PE por versão — está no livro).

import type { Element } from './ordem';

export type RitualCircle = 1 | 2 | 3 | 4;

// Custo base por círculo (Tabela 5.2, pg 129 do livro) — 1º=1 PE, 2º=3 PE,
// 3º=6 PE, 4º=10 PE. Formas avançadas (discente/verdadeira) SOMAM um
// acréscimo próprio de cada ritual a esse base — não são cumulativas entre
// si (a verdadeira não soma o acréscimo da discente, é uma alternativa à
// parte). Ex. do livro: Arma Atroz (1º círculo) custa 1 PE padrão, 4 PE
// discente (1+3) ou 6 PE verdadeiro (1+5) — nunca 1+3+5.
export const RITUAL_CIRCLE_COST: Record<RitualCircle, number> = { 1: 1, 2: 3, 3: 6, 4: 10 };

// Dado de efeito de uma variante do ritual, só quando o livro dá um dado
// explícito atrelado ao próprio ritual (ex. Amaldiçoar Arma: +1d6 de dano
// padrão) — a maioria dos rituais não tem isso (são testes de resistência,
// não uma rolagem de dano direta), então fica undefined na maioria.
export interface RitualDiceByVariant {
  padrao?: string;
  discente?: string;
  verdadeiro?: string;
}

export interface RitualDef {
  name: string;
  circle: RitualCircle;
  elements: Element[];
  summary: string;
  trilhaOnly?: boolean; // exige um poder de trilha específico
  // Formas avançadas (pg 131 do livro) — acréscimo de PE e o que muda no
  // efeito, só quando o ritual realmente tem essa forma (maioria não tem).
  discenteCost?: number; // acréscimo em PE sobre o custo do círculo (não o total)
  discenteEffect?: string;
  discenteRequires?: string; // ex. "Requer 2º círculo"
  verdadeiroCost?: number; // acréscimo em PE sobre o custo do círculo (não o total)
  verdadeiroEffect?: string;
  verdadeiroRequires?: string; // ex. "Requer 3º círculo e afinidade"
  rollDice?: RitualDiceByVariant;
}

