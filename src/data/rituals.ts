export const RITUAL_BY_NAME: Record<string, RitualDef> = Object.fromEntries(RITUALS.map((r) => [r.name, r]));

export type RitualVariant = 'padrao' | 'discente' | 'verdadeiro';

// Custo total em PE de uma variante — base do círculo (Tabela 5.2) +
// acréscimo da variante escolhida. As formas avançadas NÃO são cumulativas
// entre si (ver comentário em RITUAL_CIRCLE_COST acima).
export function ritualCost(def: RitualDef, variant: RitualVariant): number {
  const base = RITUAL_CIRCLE_COST[def.circle];
  if (variant === 'discente') return base + (def.discenteCost ?? 0);
  if (variant === 'verdadeiro') return base + (def.verdadeiroCost ?? 0);
  return base;
}

// Dado a rolar dessa variante, se o ritual tiver um cadastrado (ver
// RitualDiceByVariant) — cai pro padrão quando a variante específica não
// muda o dado.
export function ritualRollDice(def: RitualDef, variant: RitualVariant): string | undefined {
  if (!def.rollDice) return undefined;
  return def.rollDice[variant] ?? def.rollDice.padrao;
}

