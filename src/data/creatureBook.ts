export function createBookCreatures(): Creature[] {
  const now = Date.now();
  return BOOK.map((b) => ({
    id: uid(),
    name: b.name,
    vd: b.vd,
    descriptor: b.descriptor,
    size: b.size,
    flavor: b.flavor,
    el: b.el,
    tags: b.tags,
    source: 'livro',
    perception: b.perception,
    initiative: b.initiative,
    defense: b.defense,
    fortitude: b.fortitude,
    reflexes: b.reflexes,
    will: b.will,
    pvMax: b.pvMax,
    pvCurrent: b.pvMax,
    pvTemp: 0,
    damageResistance: b.damageResistance,
    attributes: { ...b.attributes },
    skills: b.skills.map((s) => ({ id: uid(), key: s.key, bonus: s.bonus })),
    displacement: b.displacement,
    abilities: b.abilities.map((a) => ({ id: uid(), name: a.name, description: a.description, rollDice: a.rollDice })),
    actions: b.actions.map((a) => ({ id: uid(), ...a })),
    notes: b.notes ?? '',
    updatedAt: now,
  }));
}
